ALTER TABLE "users" ADD COLUMN     "smokes" BOOLEAN NOT NULL DEFAULT false,
ADD COLUMN     "has_pets" BOOLEAN NOT NULL DEFAULT false;

-- Backfill: до этой миграции одно поле означало и терпимость, и собственное
-- поведение. Формулировка в анкете была «Питомцы ок (есть свои или не против)»
-- и «Курение ок (отношусь спокойно)», поэтому у уже ответивших нельзя отличить
-- «не против» от «сам курит». Переносим консервативно — считаем, что курит /
-- держит питомца. Так матчинг не сведёт аллергика с владельцем кота задним
-- числом; уточнить оба ответа человек сможет в редакторе профиля.
UPDATE "users" SET "smokes" = "smoking_ok", "has_pets" = "pets_ok";
