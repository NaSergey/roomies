/** Нейтральная стеклянная заливка для <Glass>.
 *  Ссылка на --glass-surface (globals.css) — тот же материал, что дают
 *  CSS-утилиты bg-glass/bg-tint. <Glass> принимает фон строкой в style и класс
 *  не видит, поэтому нужна именно переменная, а не утилита. */
export const GLASS_SURFACE_BG = 'var(--glass-surface)';

/** Оптика линзы: одна на все стеклянные элементы приложения.
 *
 *  mapSize — разрешение карты смещения, которую библиотека генерирует пиксельным
 *  циклом на канвасе и подаёт в SVG-фильтр через feImage. Ключевой параметр
 *  производительности, а НЕ внешнего вида: карта всё равно растягивается на
 *  размер элемента через preserveAspectRatio="none", поэтому на пилюле 120x40 и
 *  на карточке 400px разрешения 128 хватает с запасом. Замеры на Blink-десктопе
 *  (6 пилюль + крупная карточка, во время «дыхания» фона на свайпе):
 *
 *      mapSize=512 (умолчание библиотеки) — 6.6 fps, генерация ~41 мс/линзу
 *      mapSize=256                        —  23 fps
 *      mapSize=128                        —  60 fps, генерация ~10 мс/линзу
 *
 *  Картинка при этом расходится с 512 в среднем на 0.05–0.10 уровня из 255
 *  (затронуто <0.6% пикселей, все — на кромках антиалиасинга), то есть глазом
 *  не различается: сравнение скриншотов линз и крупной карточки показало
 *  идентичный рендер.
 *
 *  Важно: на iOS библиотека сама отключает SVG-рефракцию (см. useSupportsBackdropUrl
 *  в её исходнике — путь только для Blink), и <Glass> вырождается в обычный
 *  backdrop-filter. Всё вышесказанное касается Blink: Telegram Desktop и Android. */
export const GLASS_OPTICS = {
  frost: 2,
  sheen: 0.6,
  dispersion: 0.15,
  bend: 0.4,
  mapSize: 128,
} as const;
